let currentLang = localStorage.getItem('kickoff_lang') || 'en';

/** Translate a key for the active language (falls back to English). */
function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N['en'][key] || key;
}

/** Switch language, persist the choice, and toggle document direction. */
function changeLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('kickoff_lang', lang);
  applyLanguage();
  renderApp();
}

/** Apply the active language to all static markup and document attributes. */
function applyLanguage() {
  const isRtl = currentLang === 'ar';
  document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', currentLang);
  document.title = t('appTitle') + ' — ' + t('appSubtitle');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
}
